import sys, re, json, io
import pandas as pd
import xml.etree.ElementTree as ET
from fr import get, filing
INC = {'revenue': r'^(total )?(net )?(sales|revenues?)( \(note.*\))?$|^sales to customers|^total sales and revenues$|^sales and other operating revenues$|^total revenues?$|^total net sales$|^net revenues?$',
       'netIncome': r'^net (income|earnings)( \(loss\))?$|^net income attributable to [a-z\s.,&]+$|^profit( \(loss\))?$|^net earnings$',
       'eps': r'diluted',
       'shares': r'diluted'}
CF = {'ocf': r'net cash (provided by|from|flows from|provided by \(used (in|for)\))\s*operating activities|cash generated by operating activities',
      'capex': r'^(payments for acquisition of property|purchases? of property|capital expenditures|additions to property|acquisition of property)'}
BS = {'cash': r'^cash and cash equivalents( \(note.*\))?$',
      'securities': r'^(marketable (debt )?securities|short-term investments|marketable securities - current|short-term marketable securities)( \(note.*\))?$',
      'debt': r'^(commercial paper|term debt|short-term (borrowings|debt)|loans and notes payable|notes payable|current portion of long-term debt|long-term debt( due within one year| due after one year)?|long-term debt, excluding current portion|long-term debt, net|debt due within one year)( \(note.*\))?$',
      'equity': r"^total (shareholders|stockholders)['’]? equity$|^total .*(shareholders|stockholders)['’]? equity$"}
def num(v):
    if not isinstance(v, str) or not re.search(r'\d', v): return None
    neg = '(' in v
    v = re.sub(r'[^\d.]', '', v)
    try: x = float(v)
    except: return None
    return -x if neg else x
def stmts(cik, acc):
    base = f'https://www.sec.gov/Archives/edgar/data/{int(cik)}/{acc.replace("-","")}/'
    fs = ET.fromstring(get(base + 'FilingSummary.xml'))
    out = []
    for r in fs.iter('Report'):
        if (r.findtext('MenuCategory') or '') == 'Statements':
            out.append((r.findtext('ShortName') or '', base + r.findtext('HtmlFileName')))
    return out
def kind(name):
    n = name.lower()
    if 'parenthetical' in n or 'comprehensive' in n or ('equity' in n and 'balance' not in n and 'financial position' not in n): return None
    if 'cash flow' in n: return 'cf'
    if 'balance' in n or 'financial position' in n or 'condition' in n: return 'bs'
    if 'operations' in n or 'income' in n or 'earnings' in n: return 'inc'
    return None
def scan(cik, form, n=0):
    acc, rd, fd = filing(cik, form, n)
    res = {'acc': acc, 'reportDate': rd, 'filed': fd, 'vals': {}, 'rows': []}
    for name, url in stmts(cik, acc):
        k = kind(name)
        if not k: continue
        html = get(url).decode('utf-8', 'ignore')
        scale = 1e6 if re.search(r'in millions', html, re.I) else 1e3 if re.search(r'in thousands', html, re.I) else 1
        sh_scale = 1e3 if re.search(r'shares in thousands', html, re.I) else 1e6 if re.search(r'shares in millions', html, re.I) else scale
        tbl = pd.read_html(io.StringIO(html))[0]
        cols = list(tbl.columns)
        # pick the year-to-date column group for 10-Q income and cash-flow statements
        ci = [1, 2]
        if form == '10-Q' and k in ('inc', 'cf') and isinstance(cols[0], tuple):
            groups = {}
            for j, c in enumerate(cols[1:], 1):
                m = re.search(r'(\d+) Months Ended', str(c[0]))
                if m: groups.setdefault(int(m.group(1)), []).append(j)
            if groups: ci = groups[max(groups)][:2]
        pats = {'inc': INC, 'cf': CF, 'bs': BS}[k]
        for _, row in tbl.iterrows():
            label = re.sub(r'\s+', ' ', str(row.iloc[0])).strip()
            if k == 'bs' and re.search(r'total liabilities and', label, re.I): break
            for key, p in pats.items():
                if not re.search(p, label, re.I): continue
                if key == 'eps' and (not re.search(r'per share|dollars|usd', label, re.I) or re.search(r'continuing|discontinu', label, re.I)): continue
                if key == 'shares' and (re.search(r'per share|dollars|usd', label, re.I) or not re.search(r'share|diluted \(in|^diluted$', label, re.I)): continue
                if key == 'netIncome' and re.search(r'noncontrolling|per share', label, re.I): continue
                if re.search(r'lease|operating', label, re.I) and key == 'debt': continue
                a = num(row.iloc[ci[0]]) if len(row) > ci[0] else None
                b = num(row.iloc[ci[1]]) if len(ci) > 1 and len(row) > ci[1] else None
                sc = 1 if key == 'eps' else sh_scale if key == 'shares' else scale
                if a is None: continue
                res['rows'].append([k, key, label, a * sc, (b * sc) if b is not None else None])
                if key in ('debt', 'securities'):
                    res['vals'][key] = res['vals'].get(key, 0) + a * sc
                elif key not in res['vals']:
                    res['vals'][key] = a * sc
                    res['vals'][key + '_prior'] = (b * sc) if b is not None else None
    return res
if __name__ == '__main__':
    cik = sys.argv[1]
    out = {'k': scan(cik, '10-K'), 'q': scan(cik, '10-Q')}
    print(json.dumps(out))
